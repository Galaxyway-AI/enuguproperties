import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const version = "2026-10-17";
const effectiveDate = "17 October 2026";
const modulePath = "lib/legal-documents.generated.ts";
const original = await readFile(modulePath, "utf8");
const prefix = "export const approvedLegalDocuments = ";
const start = original.indexOf(prefix);
if (start < 0 || !original.trimEnd().endsWith("as const;")) {
  throw new Error("Unexpected legal document module format");
}
const documents = JSON.parse(
  original.slice(start + prefix.length, original.lastIndexOf(" as const;")),
);
const migration = [
  "-- Publish the corrected registered address as new legal versions.",
  "-- Keep previously accepted versions unchanged for the audit trail.",
];

for (const slug of ["terms", "privacy", "seller-terms"]) {
  const document = documents[slug];
  const markdown = (await readFile(`content/legal/${document.sourceFile}`, "utf8"))
    .replaceAll("\r\n", "\n");
  if (markdown.includes("House 10") || !markdown.includes(effectiveDate)) {
    throw new Error(`The ${slug} source does not contain the expected address and date.`);
  }
  const sha256 = createHash("sha256").update(markdown).digest("hex");
  Object.assign(document, { effectiveDate, version, sha256, markdown });
  const tag = `$enugu_${document.kind}_20261017$`;
  migration.push(
    `update public.agreement_versions set active=false where kind='${document.kind}' and active;`,
    "insert into public.agreement_versions(kind,version,content,sha256,legal_approved,active)",
    `values('${document.kind}','${version}',${tag}${markdown}${tag},'${sha256}',true,true)`,
    "on conflict(kind,version) do update set legal_approved=true,active=true;",
    "",
  );
}

await writeFile(
  modulePath,
  "// Generated by scripts/build-address-legal.mjs. Do not edit by hand.\n" +
    `export const approvedLegalDocuments = ${JSON.stringify(documents, null, 2)} as const;\n`,
);
await writeFile(
  "supabase/migrations/0025_registered_address_legal_versions.sql",
  migration.join("\n"),
);
