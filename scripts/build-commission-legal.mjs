import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const modulePath = "lib/legal-documents.generated.ts";
const original = await readFile(modulePath, "utf8");
const prefix = "export const approvedLegalDocuments = ";
const start = original.indexOf(prefix);
if (start < 0 || !original.trimEnd().endsWith("as const;")) {
  throw new Error("Unexpected legal document module format");
}
const documents = JSON.parse(original.slice(start + prefix.length, original.lastIndexOf(" as const;")));
const migration = [
  "-- Publish new commission wording without altering accepted historical versions.",
  "-- Business-approved draft: obtain qualified Nigerian legal review.",
];
for (const slug of ["terms", "seller-terms"]) {
  const document = documents[slug];
  const markdown = (await readFile(`content/legal/${document.sourceFile}`, "utf8")).replaceAll("\r\n", "\n");
  const sha256 = createHash("sha256").update(markdown).digest("hex");
  Object.assign(document, {
    effectiveDate: "13 October 2026",
    version: "2026-10-13",
    sha256,
    markdown,
  });
  const tag = `$enugu_${document.kind}_20261013$`;
  migration.push(
    `update public.agreement_versions set active=false where kind='${document.kind}' and active;`,
    "insert into public.agreement_versions(kind,version,content,sha256,legal_approved,active)",
    `values('${document.kind}','2026-10-13',${tag}${markdown}${tag},'${sha256}',true,true)`,
    "on conflict(kind,version) do update set legal_approved=true,active=true;",
    "",
  );
}
await writeFile(modulePath,
  "// Generated by scripts/build-commission-legal.mjs. Do not edit by hand.\n" +
  `export const approvedLegalDocuments = ${JSON.stringify(documents, null, 2)} as const;\n`);
await writeFile("supabase/migrations/0024_commission_legal_versions.sql", migration.join("\n"));
