import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { basename, dirname, resolve } from "node:path";

const documents = [
  {
    slug: "terms",
    kind: "terms",
    title: "Terms of Use",
    effectiveDate: "14 September 2026",
    source:
      "C:/Users/frank/.codex/attachments/feb610d6-4098-48ef-ba11-253cf778d69d/pasted-text.txt",
  },
  {
    slug: "privacy",
    kind: "privacy",
    title: "Privacy Policy",
    effectiveDate: "14 September 2026",
    source:
      "C:/Users/frank/.codex/attachments/d610f5cf-3970-4444-ac29-9aea68f68a27/pasted-text.txt",
  },
  {
    slug: "seller-terms",
    kind: "seller",
    title: "Seller Terms & Property Marketing Mandate",
    effectiveDate: "14 September 2026",
    source:
      "C:/Users/frank/.codex/attachments/ed334212-c184-4669-accc-05e154ccabe3/pasted-text.txt",
  },
];

const targetDirectory = resolve("content/legal");
await mkdir(targetDirectory, { recursive: true });

const output = {};
const sqlDocuments = [];
for (const document of documents) {
  const markdown = (await readFile(document.source, "utf8")).replaceAll(
    "\r\n",
    "\n",
  );
  const sha256 = createHash("sha256").update(markdown).digest("hex");
  const target = resolve(targetDirectory, `${document.slug}.md`);
  await writeFile(target, markdown);
  output[document.slug] = {
    kind: document.kind,
    title: document.title,
    effectiveDate: document.effectiveDate,
    version: "2026-09-14",
    sha256,
    markdown,
    sourceFile: basename(target),
  };
  sqlDocuments.push({ ...document, markdown, sha256 });
}

const modulePath = resolve("lib/legal-documents.generated.ts");
await mkdir(dirname(modulePath), { recursive: true });
await writeFile(
  modulePath,
  `// Generated by scripts/import-legal-documents.mjs. Do not edit by hand.\n` +
    `export const approvedLegalDocuments = ${JSON.stringify(output, null, 2)} as const;\n`,
);

const migration = [
  "-- Publish the owner-approved 14 September 2026 legal documents.",
  "-- Historical text remains immutable; only availability flags may change.",
  ...sqlDocuments.flatMap((document) => {
    const tag = `$enugu_${document.kind}_20260914$`;
    return [
      `update public.agreement_versions set active=false where kind='${document.kind}' and active;`,
      `insert into public.agreement_versions(kind,version,content,sha256,legal_approved,active)`,
      `values('${document.kind}','2026-09-14',${tag}${document.markdown}${tag},'${document.sha256}',true,true)`,
      `on conflict(kind,version) do update set legal_approved=true,active=true;`,
      "",
    ];
  }),
].join("\n");
await writeFile(
  resolve("supabase/migrations/0011_approved_legal_documents.sql"),
  migration,
);

console.log(`Imported ${documents.length} approved legal documents.`);
